const command = process.argv[2] || 'list';

switch (command) {
  case 'list': {
    console.log(`\n============================================================`);
    console.log(`🚀 MASTER BACKLINK & DIRECTORY CATALOG (105 PLATFORMS)`);
    console.log(`============================================================\n`);
    console.table(
      BACKLINK_PLATFORMS.map((p) => ({
        ID: p.id,
        Name: p.name,
        DR: p.dr,
        Tier: p.tier,
        Category: p.type,
      }))
    );
    console.log(`\nTotal Platforms: ${BACKLINK_PLATFORMS.length}`);
    console.log(`Average Domain Rating (DR): ${(BACKLINK_PLATFORMS.reduce((acc, p) => acc + p.dr, 0) / BACKLINK_PLATFORMS.length).toFixed(1)}`);
    break;
  }

  case 'export-json': {
    const outPath = path.resolve('dist/backlinks-100-plus.json');
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(
      outPath,
      JSON.stringify({ platforms: BACKLINK_PLATFORMS, profile: SUBMISSION_PROFILES }, null, 2)
    );
    console.log(`✅ Exported JSON database to ${outPath}`);
    break;
  }

  case 'export-csv': {
    const outPath = path.resolve('dist/backlinks-100-plus.csv');
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    const headers = ['ID', 'Platform Name', 'DR', 'Tier', 'Category', 'Website', 'Submission URL', 'Strategy / Notes'];
    const rows = BACKLINK_PLATFORMS.map((p) => [
      p.id,
      `"${p.name.replace(/"/g, '""')}"`,
      p.dr,
      `"${p.tier}"`,
      `"${p.type}"`,
      `"${p.website}"`,
      `"${p.submitUrl}"`,
      `"${p.notes.replace(/"/g, '""')}"`,
    ]);
    const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
    fs.writeFileSync(outPath, csvContent, 'utf8');
    console.log(`✅ Exported CSV database to ${outPath}`);
    break;
  }

  case 'profiles': {
    console.log(`\n============================================================`);
    console.log(`📋 COPY-PASTE SUBMISSION PROFILES FOR DIRECTORIES`);
    console.log(`============================================================\n`);
    console.log(JSON.stringify(SUBMISSION_PROFILES, null, 2));
    break;
  }

  default:
    console.log(`Usage: node scripts/backlink-manager.mjs [list | export-json | export-csv | profiles]`);
}
